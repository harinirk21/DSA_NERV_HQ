
import csv
from pathlib import Path

import matplotlib.pyplot as plt
import networkx as nx

ROOT = Path(__file__).resolve().parent.parent
DATA_FILE = ROOT / "data" / "flights.csv"
ROUTE_FILE = ROOT / "output" / "route.csv"
OUTPUT_FILE = ROOT / "output" / "flight_graph.png"


# Create a graph of all available flights.
graph = nx.DiGraph()

with open(DATA_FILE, "r", newline="") as file:
    reader = csv.DictReader(file)

    for row in reader:
        source = int(row["source"])
        destination = int(row["destination"])
        price = int(row["price"])

        graph.add_edge(source, destination, price=price)


# Read the cheapest route generated by traveller.py.
route_edges = []

with open(ROUTE_FILE, "r", newline="") as file:
    reader = csv.DictReader(file)

    for row in reader:
        route_edges.append(
            (int(row["source"]), int(row["destination"]))
        )


# Arrange cities and draw all flights.
positions = nx.spring_layout(graph, seed=42)

plt.figure(figsize=(10, 7))

nx.draw_networkx_nodes(
    graph, positions, node_size=1400
)

nx.draw_networkx_labels(
    graph, positions, font_size=12, font_weight="bold"
)

# Draw regular flights.
nx.draw_networkx_edges(
    graph,
    positions,
    edgelist=list(graph.edges()),
    edge_color="gray",
    arrows=True,
    arrowsize=20,
    connectionstyle="arc3,rad=0.08",
)

# Highlight the selected cheapest route.
nx.draw_networkx_edges(
    graph,
    positions,
    edgelist=route_edges,
    edge_color="red",
    width=3,
    arrows=True,
    arrowsize=25,
    connectionstyle="arc3,rad=0.08",
)

# Show original flight prices on the edges.
edge_labels = {
    (u, v): f"₹{data['price']}"
    for u, v, data in graph.edges(data=True)
}

nx.draw_networkx_edge_labels(
    graph,
    positions,
    edge_labels=edge_labels,
    font_size=9,
    label_pos=0.5,
)

plt.title("Budget Traveller: Flight Network and Cheapest Route")
plt.axis("off")
plt.tight_layout()

OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
plt.savefig(OUTPUT_FILE, dpi=200, bbox_inches="tight")
plt.close()

print(f"Visualization saved to: {OUTPUT_FILE}")
